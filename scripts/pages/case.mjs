// A case page: one of the eight sites, in one language. Name, sector and place; the site's opening
// (recorded live) in a browser; the project; the direction with the site's own palette and type;
// the interface (three desktop screens and two phone screens of the live site); the movement;
// what Josean did; the next case and the way back.
import { projects, bySlug } from '../../src/data/projects.js';
import { esc, img, video, head, header, footer, homeUrl, caseUrl, LOCALES, GLOBE, ICONS } from './shared.mjs';

const N = String(projects.length).padStart(2, '0');
const srcset = (base, widths) => widths.map((w) => `${img(`${base}-${w}`)} ${w}w`).join(', ');
const host = (url) => new URL(url).host;
const ARROW = (id) => `<svg class="icon" aria-hidden="true"><use href="#${id}" /></svg>`;
// the case page sits on the portfolio's graphite: a dark site lends its accent (labels, button);
// a light site (Chez TonTon, isola) lends its own light ground, which reads on graphite
const pageColours = (p) =>
  p.theme === 'light'
    ? `--accent: ${p.bg}; --s-btn: ${p.bg}; --s-bg: ${p.ink}`
    : `--accent: ${p.label || p.accent}; --s-btn: ${p.button || p.accent}; --s-bg: ${p.bg}`;

export function casePage(loc, t, i) {
  const p = projects[i];
  const c = t.cases[p.slug];
  const L = t.casePage;
  const next = projects[(i + 1) % projects.length];
  const alternates = Object.fromEntries(LOCALES.map((l) => [l.code, caseUrl(l, p.slug)]));
  const visit = (cls = 'btn btn--site') => `<a class="${cls}" href="${p.url}" target="_blank" rel="noopener">
                <span>${esc(t.work.visit)}</span>
                ${ARROW('i-external')}
                <span class="sr-only">${esc(t.newTab)}</span>
              </a>`;
  const shots = [1, 2, 3]
    .map(
      (n) => `<figure class="shot" data-reveal>
              <p class="browser-bar"><i></i><i></i><i></i><span>${host(p.url)}</span></p>
              <img src="${img(`site-${p.slug}-s${n}-1280`)}" srcset="${srcset(`site-${p.slug}-s${n}`, [720, 1280])}" sizes="(min-width: 1024px) 60vw, 92vw" width="1280" height="800" alt="${esc(L.shotAlt(p.name, n + 1))}" loading="lazy" decoding="async" />
            </figure>`,
    )
    .join('\n            ');
  const phones = [0, 1]
    .map(
      (n) => `<figure class="phone phone--static" data-reveal><img src="${img(`site-${p.slug}-m${n}-390`)}" srcset="${srcset(`site-${p.slug}-m${n}`, [390, 780])}" sizes="(min-width: 1024px) 18vw, 44vw" width="390" height="844" alt="${esc(L.phoneAlt(p.name, n + 1))}" loading="lazy" decoding="async" /></figure>`,
    )
    .join('\n              ');
  const extra = `    <script>
      document.documentElement.classList.remove('no-js');
      document.documentElement.classList.add('js');
      if (!window.matchMedia('(prefers-reduced-motion: reduce)').matches) document.documentElement.classList.add('motion-ok');
    </script>
    <script type="module" src="/src/case.js"></script>
`;

  return `<!doctype html>
<!-- Generated by scripts/build-pages.mjs from scripts/pages/case.mjs and src/i18n/${loc.code}.js: edit those, then run npm run pages. -->
<html lang="${loc.html}" class="no-js">
  ${head({
    loc,
    t,
    title: `${p.name} · ${t.categories[p.category].name} · Josean Araújo`,
    description: L.description(p.name, c.proposal, `${c.sector}, ${c.place}`),
    ogType: 'article',
    ogTitle: `${p.name} · ${c.tagline}`,
    ogDescription: c.proposal,
    alternates,
    extra,
  })}
  <body class="study-page study-page--${p.theme}" style="${pageColours(p)}">
    <a class="skip-link" href="#conteudo">${esc(t.skip)}</a>

    <svg class="icon-sprite" aria-hidden="true" focusable="false">
      ${ICONS}
      ${GLOBE}
    </svg>

    ${header({ loc, t, alternates, study: true })}

    <main id="conteudo" class="study" tabindex="-1">
      <!-- 1 · name, sector, the opening of the live site -->
      <section class="study-hero" aria-labelledby="study-title">
        <div class="wrap study-hero-grid">
          <div class="study-intro" data-reveal>
            <a class="back" href="${homeUrl(loc)}#${p.slug}">
              ${ARROW('i-arrow-left')}
              <span>${esc(L.back)}</span>
            </a>
            <p class="eyebrow"><span>${p.number} / ${N}</span> ${esc(t.categories[p.category].name)}</p>
            <h1 class="study-title" id="study-title">${esc(p.name)}</h1>
            <p class="case-sector">${esc(c.sector)} · ${esc(c.place)}</p>
            <p class="study-lead">${esc(c.proposal)}</p>
            <div class="actions">
              ${visit()}
            </div>
          </div>
          <figure class="study-window" data-reveal>
            <div class="browser">
              <p class="browser-bar"><i></i><i></i><i></i><span>${host(p.url)}</span></p>
              <video class="browser-screen" muted loop playsinline preload="metadata" poster="${img(`poster-${p.slug}-1280`)}" data-loop>
                <source src="${video(`${p.slug}-loop`)}" type="video/mp4" />
              </video>
            </div>
            <figcaption>${esc(t.work.loop)}</figcaption>
          </figure>
        </div>
      </section>

      <div class="wrap study-body">
        <!-- 2 · the project -->
        <section class="study-block" aria-labelledby="projeto" data-reveal>
          <h2 class="study-h2" id="projeto"><span>02</span> ${esc(L.overview)}</h2>
          <p class="study-text">${esc(c.overview)}</p>
          <ul class="case-tags" aria-label="${esc(L.tags)}">${c.tags.map((x) => `<li>${esc(x)}</li>`).join('')}</ul>
        </section>

        <!-- 3 · the direction, with the site's own palette and type -->
        <section class="study-block" aria-labelledby="direcao" data-reveal>
          <h2 class="study-h2" id="direcao"><span>03</span> ${esc(L.direction)}</h2>
          <dl class="direction">
${Object.entries(L.directionLabels)
  .map(([k, label]) => `            <div>\n              <dt>${esc(label)}</dt>\n              <dd>${esc(c.direction[k])}</dd>\n            </div>`)
  .join('\n')}
          </dl>
          <div class="palette">
            <p class="palette-label">${esc(L.palette)}</p>
            <ul class="swatches">
              ${p.tokens.map(([name, hex]) => `<li><span class="swatch" style="--sw: ${hex}"></span><span class="swatch-name">${esc(name)}</span><span class="swatch-hex">${hex}</span></li>`).join('\n              ')}
            </ul>
            <p class="palette-label">${esc(L.fonts)}</p>
            <p class="palette-fonts">${esc(p.fonts)}</p>
          </div>
        </section>

        <!-- 4 · the interface: the live site, desktop and phone -->
        <section class="study-block study-block--wide" aria-labelledby="interface">
          <h2 class="study-h2" id="interface" data-reveal><span>04</span> ${esc(L.interface)}</h2>
          <div class="shots">
            ${shots}
          </div>
          <div class="phones">
            <p class="palette-label" data-reveal>${esc(L.phone)}</p>
            <div class="phones-row">
              ${phones}
            </div>
          </div>
        </section>

        <!-- 5 · the movement -->
        <section class="study-block" aria-labelledby="movimento" data-reveal>
          <h2 class="study-h2" id="movimento"><span>05</span> ${esc(L.movement)}</h2>
          <ol class="motion-states">
${c.motion.map((m, j) => `            <li><span>${String(j + 1).padStart(2, '0')}</span> ${esc(m)}</li>`).join('\n')}
          </ol>
          <p class="study-text">${esc(c.script)}</p>
        </section>

        <!-- 6 · what Josean did -->
        <section class="study-block" aria-labelledby="papel" data-reveal>
          <h2 class="study-h2" id="papel"><span>06</span> ${esc(L.role)}</h2>
          <p class="study-text">${esc(c.role)}</p>
          <div class="actions">
            ${visit('btn btn--site btn--lg')}
          </div>
        </section>
      </div>

      <!-- 7 · next case and the way back -->
      <nav class="study-next" aria-label="${esc(L.nav)}">
        <div class="wrap study-next-inner">
          <a class="next-link" href="${caseUrl(loc, next.slug)}">
            <span class="eyebrow">${esc(L.next)}</span>
            <span class="next-name">${esc(next.name)}</span>
            <span class="next-line">${esc(t.cases[next.slug].sector)} · ${esc(t.cases[next.slug].place)}</span>
            ${ARROW('i-arrow-right')}
          </a>
          <a class="back" href="${homeUrl(loc)}#indice">
            ${ARROW('i-arrow-left')}
            <span>${esc(L.all)}</span>
          </a>
        </div>
      </nav>
    </main>

    ${footer({ loc, t, note: t.footer.caseNote(p.name), study: true })}
  </body>
</html>
`;
}
